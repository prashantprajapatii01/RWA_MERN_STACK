const mongoose = require("mongoose")

const contactUsSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
    trim: true
  },
  email: {
    type: String,
    required: true,
    trim: true
  },
  phone: {
    type: String,
    required: true,
    trim: true
  },
  subject: {
    type: String,
    required: true,
    trim: true
  },
  message: {
    type: String,
    required: true,
    trim: true
  },
  status: {
    type: Boolean,
    default: true   // Active
  }
}, { timestamps: true })  // gives createdAt

module.exports = mongoose.model("ContactUs", contactUsSchema)